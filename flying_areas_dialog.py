import os

from qgis.core import QgsPointXY
from qgis.PyQt import uic
from qgis.PyQt.QtGui import QColor
from qgis.PyQt.QtWidgets import QDockWidget
from qgis.utils import iface

from .second_window import SecondWindow
from .source.calculZone import ZoneCalculateur
from .source.drone import Drone
from .source.file_managing import File_managing
from .source.pointManager import PointManager
from .source.zone import Zone
from .source.zoneManager import ZoneManager

FORM_CLASS, _ = uic.loadUiType(os.path.join(
    os.path.dirname(__file__), 'flying_areas_dialog_base.ui'))

DOSSIER_DRONES = 'Base_drones'
RAYON_ZONE_VOL = 100       # rayon de la zone de vol autour du point de départ (m)
NB_SOMMETS_ZONE_VOL = 30   # nombre de sommets du polygone circulaire
MODE_POINT_DEPART = 0      # index de ChoixMode pour le mode « point de départ »
MIN_SOMMETS_ZONE = 3       # nombre minimum de points pour définir une zone


class FlyingAreasDialog(QDockWidget, FORM_CLASS):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setupUi(self)

        self.drones: dict[str, Drone] = {}
        self.zone_manager = ZoneManager()
        self.point_manager = PointManager(iface.mapCanvas(),self.ChoixMode.currentIndex())
        self.charger_drones()


        self.LancerCalcul.clicked.connect(self.lancer_calcul)
        self.Stop.clicked.connect(self.fermer_plugin)
        self.AjoutDrone.clicked.connect(self.ouvrir_seconde_fenetre)

        self.AltiVol.setMinimum(0)
        self.AltiVol.setMaximum(1000)
        self.VitVol.setMinimum(0)
        self.VitVol.setMaximum(1000)
        self.DensPop.setMinimum(0)
        self.DensPop.setMaximum(1000000)
        
        self.ChoixMode.currentIndexChanged.connect(self.mode_change)
        self.ChoixDrone.currentTextChanged.connect(self.afficher_donnees_drone)
        self.afficher_donnees_drone(self.ChoixDrone.currentText())

    # --- Cycle de vie ---

    def showEvent(self, event):
        super().showEvent(event)
        # Réactive la capture des clics à chaque affichage du panneau
        self.point_manager.activer()

    def closeEvent(self, event):
        self.point_manager.desactiver()
        self.zone_manager.supprimer_couche()
        super().closeEvent(event)

    # -- Mode --
    def mode_change(self, index: int) -> None:
        """Appelé à chaque changement de valeur de ChoixMode."""
        if index == MODE_POINT_DEPART:
            self._avertir("Mode point de départ : cliquez un point sur la carte.")
            self.point_manager.context = 0
        else:
            self.point_manager.context = 1
            self._avertir(f"Mode zone de départ : cliquez au moins {MIN_SOMMETS_ZONE} points sur la carte.")

        # Les points cliqués dans l'ancien mode n'ont plus de sens dans le nouveau
        self.point_manager.clear_couche()

    # --- Calcul ---

    def lancer_calcul(self):
        drone = self.drones.get(self.ChoixDrone.currentText())
        if drone is None:
            self._avertir("Aucun drone valide sélectionné.")
            return

        points = list(self.point_manager.points)
        zone_vol = self._construire_zone_vol(points)
        if zone_vol is None:
            return

        zone_calc = ZoneCalculateur(flying_area=zone_vol)
        try:
            zone_calc.calculate_areas(drone)
        except ValueError as erreur:
            self._avertir(str(erreur))
            return

        # Calcul réussi : les points sont consommés, la couche reste affichée
        self.point_manager.vider()

        # Ordre important : la zone de vol est prioritaire, puis buffer, puis contingence
        self.zone_manager.supprimer_couche()
        self.zone_manager.ajouter_zone(zone_calc.flying_area)
        self.zone_manager.ajouter_zone(zone_calc.buffering_area)
        self.zone_manager.ajouter_zone(zone_calc.contingency_area)

    def _construire_zone_vol(self, points: list[QgsPointXY]) -> Zone | None:
        """Construit la zone de vol selon le mode choisi. Renvoie None si les points sont insuffisants."""
        if self.ChoixMode.currentIndex() == MODE_POINT_DEPART:
            if not points:
                self._avertir("Cliquez un point de départ sur la carte.")
                return None
            zone = Zone([], QColor("green"), 3, "fly")
            # Le dernier point cliqué sert de point de départ
            #zone.create_zone_from_point(points[-1], RAYON_ZONE_VOL, NB_SOMMETS_ZONE_VOL)
            #FIXME: Essaie pour voir comment ça fonctionne
            zone.create_zone_from_point(points[-1],10,NB_SOMMETS_ZONE_VOL)#, RAYON_ZONE_VOL, NB_SOMMETS_ZONE_VOL)
            if not zone.is_valid():
                self._avertir("La zone n'est pas valide")
                return None
            return zone

        if len(points) < MIN_SOMMETS_ZONE:
            self._avertir(f"Cliquez au moins {MIN_SOMMETS_ZONE} points pour définir la zone.")
            return None
        zone = Zone(points, QColor("green"), 3, "fly")
        if not zone.is_valid():
            self._avertir("La zone n'est pas valide")
            return None
        return zone

    # --- Drones ---

    def charger_drones(self):
        """Lit les fichiers .txt du dossier Base_drones (un fichier = un drone)."""
        self.ChoixDrone.clear()
        self.drones = {}

        dossier = os.path.join(os.path.dirname(__file__), DOSSIER_DRONES)
        if not os.path.isdir(dossier):
            self._avertir(f"Dossier des drones introuvable : {dossier}")
            return

        for fichier in sorted(os.listdir(dossier)):
            if not fichier.lower().endswith('.txt'):
                continue
            chemin = os.path.join(dossier, fichier)
            try:
                drone = File_managing.read(chemin)
            except (OSError, ValueError) as erreur:
                self._avertir(f"Impossible de lire {fichier} : {erreur}")
                continue
            self.drones[drone.get_name()] = drone
            self.ChoixDrone.addItem(drone.get_name())
    
    @staticmethod
    def _fmt(valeur) -> str:
        return "-" if valeur is None else f"{valeur:g}"

    def afficher_donnees_drone(self, nom: str) -> None:
        """Affiche les données du drone sélectionné dans le chapitre « Drone »."""
        drone = self.drones.get(nom)
        if drone is None:
            for label in (self.DroneNom, self.DroneType, self.DroneRadioDist,
                          self.DroneAirSpeed, self.DroneBufferDist):
                label.setText("-")
            return
        self.DroneNom.setText(drone.get_name())
        self.DroneType.setText(drone.get_drone_type() or "-")
        self.DroneRadioDist.setText(self._fmt(drone.get_radio_dist()))
        self.DroneAirSpeed.setText(self._fmt(drone.get_air_speed()))
        self.DroneBufferDist.setText(self._fmt(drone.get_buffer_dist()))

    # --- Actions des boutons ---

    def fermer_plugin(self):
        self.AltiVol.setValue(0)
        self.VitVol.setValue(0)
        self.DensPop.setValue(0)
        self.close()  # déclenche closeEvent, qui nettoie les couches

    def ouvrir_seconde_fenetre(self):
        self.second_window = SecondWindow(None)
        self.second_window.show()

    def accept(self):
        """Évite l'erreur de signal accept() hérité de l'ancien QDialog."""
        pass

    def _avertir(self, message: str) -> None:
        iface.messageBar().pushWarning("Zones de vol", message)
    
